"""模块四：本地文件列表（书籍目录式浏览）。

### 它解决什么

本机目录一多，资源管理器那种一行一条的列表就不好用了：看不到层级全貌、
分不清哪一层是关键、没法一眼判断"这一卷有多厚"。所以这里把目录树渲染成
**一本书的目录页** —— 分卷、分章、编号（1 / 1.1 / 1.1.1）、点线引导、
后面跟着条目数与占用大小。扫描一遍就知道自己有哪些东西、放在哪一层。

### 形态：`native`（同进程挂载）

- 只需要读文件系统，没有长任务、没有外部依赖（纯标准库 + FastAPI）
- 不起端口、不起进程 —— 少一个端口就少一处要防的地方
- 它**自带页面**：HTML/CSS/JS 都由本模块托管（`web/` 下），
  中台的「模块」面板一点就能用，不需要往中台首页里塞代码

### ⛔ 只读边界（这条不许放宽，也不要"优化"掉）

- 全程**只读**：不写、不删、不移、不改名任何文件。没有任何写文件系统的接口
- 不提供文件内容读取、不提供下载、不提供打开动作 —— 那些是别的能力的范围
- 路径做**包含性校验**：所有请求的路径都必须解析后仍落在用户登记的根目录内。
  `..` 与指向外部的符号链接都在 `lister.resolve_in_root()` 里被拒
- 不提供任何形式的命令执行

### 数据存哪

用户登记的「书库」根目录写在模块自己的 `data/libraries.json` 里 ——
各模块数据各归各家，中台不越权读写（这条对写入方向同样成立）。
"""

MODULE = ModuleSpec(
    id="filelist",
    name="本地文件列表",
    description=(
        "把本机目录读成一本「书的目录」：分卷分章、层级编号、点线引导，"
        "带条目数与占用大小；可登记多个书库，全程只读"
    ),
    version="1.0",
    order=20,
    kind="native",
    app_module="filelist_api",
    router_object="router",
    license="自有项目（本项目自研，非第三方）",
    note=(
        "只读浏览：不写、不删、不移、不改名任何文件，也没有下载或打开动作。"
        "路径做包含性校验，`..` 与指向根目录之外的符号链接都会被拒。"
    ),
)
